/**
 * Intelligent food search with accent-insensitive matching,
 * token split matching, and relevance ranking.
 */
export function searchFoods(query: string): FoodItem[] {
  const raw = query.trim();
  if (!raw) {
    // Show top common Vietnamese staples first
    return SEED_FOODS.slice(0, 20);
  }

  const normQuery = removeVietnameseTones(raw);
  const terms = normQuery.split(/\s+/).filter(Boolean);

  const scored: Array<{ item: FoodItem; score: number }> = [];

  for (const item of SEED_FOODS) {
    const normName = removeVietnameseTones(item.name);
    const normStd = removeVietnameseTones(item.standardizedName);
    const normKeywords = (item.keywords || []).map(removeVietnameseTones);

    let matchAllTerms = true;
    for (const t of terms) {
      const inName = normName.includes(t);
      const inStd = normStd.includes(t);
      const inKw = normKeywords.some((kw) => kw.includes(t));
      if (!inName && !inStd && !inKw) {
        matchAllTerms = false;
        break;
      }
    }

    if (!matchAllTerms) continue;

    // Calculate relevance score
    let score = 0;
    if (normName === normQuery) {
      score += 100;
    } else if (normKeywords.some((kw) => kw === normQuery)) {
      score += 90;
    } else if (normName.startsWith(normQuery)) {
      score += 60;
    } else if (normName.includes(normQuery)) {
      score += 40;
    } else {
      score += 20;
    }

    // Shorter names slightly preferred over very long descriptions
    score += Math.max(0, 30 - item.name.length * 0.3);

    scored.push({ item, score });
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.map((s) => s.item);
}
